// Writes test/test_guard/guard_fixture.h from the designer's reference runs
// (schaltli-designer lib/fixtures/guard-spans.json):
//
//   node tools/guard-fixture.js [path/to/guard-spans.json]
const fs = require("fs")
const path = require("path")
const src = process.argv[2] || path.join(__dirname, "..", "..", "schaltli-designer", "lib", "fixtures", "guard-spans.json")
const fixture = JSON.parse(fs.readFileSync(src, "utf8"))
const flat = (runs) => runs.map((row, y) => row.map(([a, b]) => `{${y},${a},${b}}`).join(",")).filter(Boolean).join(",")
let out = "// Generated by tools/guard-fixture.js from schaltli-designer lib/fixtures/guard-spans.json - do not edit.\n#pragma once\n\nstruct GuardRun { short y, a, b; };\nstruct GuardCase { int size; const GuardRun* lock; int lockN; const GuardRun* arrows; int arrowsN; };\n\n"
fixture.cases.forEach((c) => {
  const lock = c.lock.flatMap((row, y) => row.map(() => 0)).length
  const arrows = c.arrows.flatMap((row) => row).length
  out += `static const GuardRun LOCK_${c.size}[] = {${flat(c.lock)}};\nstatic const GuardRun ARROWS_${c.size}[] = {${flat(c.arrows)}};\n`
})
out += `\nstatic const GuardCase GUARD_CASES[] = {\n${fixture.cases.map((c) => `  {${c.size}, LOCK_${c.size}, ${c.lock.flat().length}, ARROWS_${c.size}, ${c.arrows.flat().length}},`).join("\n")}\n};\nstatic const int GUARD_CASE_COUNT = ${fixture.cases.length};\n`
fs.writeFileSync(path.join(__dirname, "..", "test", "test_guard", "guard_fixture.h"), out)
console.log("wrote", fixture.cases.length, "cases")
