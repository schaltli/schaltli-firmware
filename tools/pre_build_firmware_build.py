Import("env")

import os
import subprocess

# Writes src/FirmwareBuild.h - the identity of the source a firmware was
# built from - before every build.
#
# Every board announced FIRMWARE_VERSION "0.1.0" in its hello from the day it
# was ported, so nothing could tell one build from another, and an update
# over the air needs exactly that: the designer compares what a device runs
# with what a release carries (designer repo, docs/2026-09-15-firmware-ota.md,
# decision 6).
#
# The identity comes from git rather than from a number someone bumps, for
# the same reason the DDF is identified by a hash: a number a human has to
# remember is a number that goes stale. On a release tag it is the tag
# itself (fw-2026.09.15.1); after it, git's own description of the distance
# (fw-2026.09.15.1-3-g1a2b3c4d5e); with uncommitted changes, "-dirty" on the
# end - a build nobody could reproduce says so.
#
# The header is gitignored and only rewritten when its content changes, so an
# unchanged tree does not recompile everything that includes it.

REPO = env["PROJECT_DIR"]
HEADER = os.path.join(REPO, "src", "FirmwareBuild.h")


def describe():
    try:
        result = subprocess.run(
            ["git", "describe", "--tags", "--match", "fw-*", "--always", "--dirty", "--abbrev=10"],
            cwd=REPO,
            capture_output=True,
            text=True,
        )
    except (OSError, FileNotFoundError):
        return "unknown"
    if result.returncode != 0:
        return "unknown"
    return result.stdout.strip() or "unknown"


build = describe()
content = (
    "#pragma once\n"
    "// GENERATED by tools/pre_build_firmware_build.py before every build - do not edit.\n"
    '#define FIRMWARE_BUILD "' + build + '"\n'
)

try:
    with open(HEADER, "r", newline="") as f:
        current = f.read()
except OSError:
    current = None

if current != content:
    with open(HEADER, "w", newline="") as f:
        f.write(content)

print("[firmware] build " + build)
